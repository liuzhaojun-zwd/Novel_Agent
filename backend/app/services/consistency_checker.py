async def check_consistency(
    content: str, known_characters: list[str], chapter_number: int
) -> list[dict]:
    """检查章节正文中是否出现未定义的人物名称。"""
    if not known_characters:
        return []

    known_set_lower = {c.strip().lower() for c in known_characters}
    alerts = []
    seen = set()

    def is_known(name: str) -> bool:
        nl = name.lower().strip()
        if nl in known_set_lower:
            return True
        for kn in known_set_lower:
            if kn in nl or nl in kn:
                return True
        return False

    # 从连续中文序列中提取所有2字组合（重叠），然后过滤
    candidates = set()
    i = 0
    n = len(content)
    while i < n:
        c = content[i]
        if '\u4e00' <= c <= '\u9fff':
            start = i
            while i < n and '\u4e00' <= content[i] <= '\u9fff':
                i += 1
            seq = content[start:i]
            # 重叠提取：每个2字组合
            for j in range(len(seq) - 1):
                candidates.add(seq[j:j+2])
        else:
            i += 1

    for word in candidates:
        # 基本过滤
        if len(word) < 2 or word in _EXCLUDE:
            continue
        # 首字必须是姓氏
        if word[0] not in _COMMON_SURNAMES:
            continue
        # 第二字不能是动作/助词（排除"张说""林道"这类）
        if word[1] in _NON_NAME_SECOND:
            continue
        if is_known(word):
            continue
        if word not in seen:
            seen.add(word)
            alerts.append({
                "chapter_number": chapter_number,
                "conflict_name": word,
            })

    return alerts